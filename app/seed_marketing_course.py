def seed_marketing_course(db: Session):
    """Create Marketing Fundamentals course in the database"""

    # Check if course already exists
    existing_course = db.query(Course).filter(
        Course.title == MARKETING_COURSE_DATA["title"]
    ).first()

    if existing_course:
        print(f"⚠️  Course '{MARKETING_COURSE_DATA['title']}' already exists (ID: {existing_course.id})")
        return existing_course

    # Create new course
    course = Course(**MARKETING_COURSE_DATA)
    db.add(course)
    db.commit()
    db.refresh(course)

    print(f"✅ Created course: {course.title} (ID: {course.id})")
    print(f"   📚 Lessons: {course.lessons_count}")
    print(f"   📊 Track: {course.track}")
    print(f"   🎯 Level: {course.level}")

    return course


def link_marketing_simulation(db: Session, course_id: int, simulation_id: int):
    """Link existing Marketing simulation to the course"""
    simulation = db.query(Simulation).filter(Simulation.id == simulation_id).first()

    if not simulation:
        print(f"❌ Simulation with ID {simulation_id} not found")
        return

    simulation.course_id = course_id
    simulation.required_progress = 100
    simulation.unlock_message = "Поздравляем! Вы завершили Module 1 и разблокировали симуляцию 'Запуск рекламной кампании'! 🎉"

    db.commit()
    print(f"✅ Linked simulation '{simulation.title}' to course (requires 100% progress)")


